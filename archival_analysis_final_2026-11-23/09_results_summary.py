"""Write RESULTS.md from the exhibit tables, so every number in it comes straight from the output files. Usage: python 09_results_summary.py"""
import pandas as pd
from common import HERE, OUT

fp = lambda v: "< .001" if v < .001 else ("< .01" if v < .01 else "%.2f" % v).replace("0.", ".")
fe = lambda v, d=3: ("%+." + str(d) + "f") % v
L = ["# Results", "", "Generated by `09_results_summary.py` from the tables in `outputs/`. National ME list unless stated. All results are exploratory.", ""]

# ---- Exhibit 1
m = pd.read_csv(OUT / "exhibit1_label_choice.csv")
L += ["## Exhibit 1. Who positions broadly", "", "Outcome: 1 if WPME, 0 if ME. Linear probability, state fixed effects, county-clustered SEs. Coefficients in percentage points.", "",
      "| Controls | Per 10 pts Trump share | p | Trump share above 50% | p | Per 1 pt Middle Eastern ancestry | p |", "|---|---|---|---|---|---|---|"]
for ctl in m.controls.unique():
    c = m[m.me_list.eq("national") & m.controls.eq(ctl) & m.trump_measure.eq("continuous")].iloc[0]
    j = m[m.me_list.eq("national") & m.controls.eq(ctl) & m.trump_measure.eq("majority")].iloc[0]
    mena = ("%s | %s" % (fe(100 * c.mena_est, 1), fp(c.mena_p))) if pd.notna(c.mena_est) else " | "
    L.append("| %s | %s | %s | %s | %s | %s |" % (ctl, fe(100 * c.trump_est, 1), fp(c.trump_p), fe(100 * j.trump_est, 1), fp(j.trump_p), mena))
c = m[m.me_list.eq("national")].iloc[0]
L += ["", "Restaurants: %d in %d counties; %.0f%% are WPME." % (c.n, c.counties, 100 * c.share_wpme), ""]
b = pd.read_csv(OUT / "exhibit1_label_choice_bins.csv")
for var, title in [("mena", "County residents with Middle Eastern ancestry"), ("trump_share", "County Trump share")]:
    d = b[b.me_list.eq("national") & b.by.eq(var)]
    L += ["| %s | %s |" % (title, " | ".join(d.bin)), "|---|" + "---|" * len(d), "| Share WPME | %s |" % " | ".join("%.0f%%" % (100 * v) for v in d.share_wpme),
          "| Restaurants | %s |" % " | ".join(str(v) for v in d.n), ""]

# ---- Exhibit 2
v = pd.read_csv(OUT / "exhibit2_levels.csv")
v = v[v.me_list.eq("national")]
L += ["## Exhibit 2. Ordinary-times levels (background; no claim is made from this table)", "",
      "WPME minus ME in the same county, all years, restaurants with 10+ reviews. County fixed effects; county-clustered SEs. "
      "WPME requires a baba ghanoush mention and ME does not, so the second pair of columns holds the review evidence equal.", ""]
for out, title in [("mean_rating", "Rating (stars)"), ("logrev", "Review volume (log points; adds first-review-year fixed effects)")]:
    L += ["**%s**" % title, "", "| Quantity | WPME vs all ME | p | WPME vs ME with a baba mention | p |", "|---|---|---|---|---|"]
    for q in v.quantity.unique():
        a = v[v.outcome.eq(out) & v.quantity.eq(q) & v.comparison.eq("WPME vs all ME")].iloc[0]
        r = v[v.outcome.eq(out) & v.quantity.eq(q) & v.comparison.eq("WPME vs ME with a baba mention")].iloc[0]
        L.append("| %s | %s | %s | %s | %s |" % (q, fe(a.est), fp(a.p), fe(r.est), fp(r.p)))
    a = v[v.outcome.eq(out) & v.comparison.eq("WPME vs all ME")].iloc[0]
    r = v[v.outcome.eq(out) & v.comparison.eq("WPME vs ME with a baba mention")].iloc[0]
    L += ["", "Restaurants: %d WPME, %d ME (%d ME with a baba mention)." % (a.n_wpme, a.n_me, r.n_me), ""]

# ---- Exhibit 3
e = pd.read_csv(OUT / "exhibit3_events.csv")
e = e[e.me_list.eq("national")]
sb = pd.read_csv(OUT / "exhibit3_shared_baseline.csv")
sb = sb[sb.me_list.eq("national")]
L += ["## Exhibit 3. Stigma events", "", "delta = change in the WPME-minus-ME rating gap after the event, per unit of the county Trump measure. Exact review dates. "
      "Restaurant and county-by-period fixed effects; county-clustered SEs.", "", "**Focus events**", "",
      "| | Per 10 pts Trump share, first 6 weeks | SE | p | Weeks 7-18 | p | Trump share above 50%, first 6 weeks | p | Pre-period test p |", "|---|---|---|---|---|---|---|---|---|"]
def erow(name, label):
    g = lambda m, w: e[e.event.eq(name) & e.trump_measure.eq(m) & e.window.eq(w)].iloc[0]
    a, l, j = g("continuous", "first 6 weeks"), g("continuous", "weeks 7-18"), g("majority", "first 6 weeks")
    return "| %s | %s | %.3f | %s | %s | %s | %s | %s | %s |" % (label, fe(a.est), a.se, fp(a.p), fe(l.est), fp(l.p), fe(j.est), fp(j.p), fp(a.pretrend_p) if pd.notna(a.pretrend_p) else "")
L += [erow("2016 election", "2016 election (Nov 8, 2016)"), erow("Travel ban", "Travel ban (Jan 27, 2017)"), erow("POOLED: election and travel ban", "Both pooled")]
for q, lab in [("delta: after election", "Shared baseline: election"), ("delta: after travel ban", "Shared baseline: travel ban"), ("delta: average of the two", "Shared baseline: average")]:
    a = sb[sb.quantity.eq(q) & sb.trump_measure.eq("continuous")].iloc[0]
    j = sb[sb.quantity.eq(q) & sb.trump_measure.eq("majority")].iloc[0]
    L.append("| %s | %s | %.3f | %s | | | %s | %s | |" % (lab, fe(a.est), a.se, fp(a.p), fe(j.est), fp(j.p)))
a = e[e.event.eq("2016 election") & e.trump_measure.eq("continuous") & e.window.eq("first 6 weeks")].iloc[0]
bn = e[e.event.eq("Travel ban") & e.trump_measure.eq("continuous") & e.window.eq("first 6 weeks")].iloc[0]
L += ["", "Election: %d restaurants, %d counties, %d reviews in the six weeks after. Travel ban: %d restaurants, %d counties, %d reviews." % (
    a.restaurants, a.counties, a.reviews_after, bn.restaurants, bn.counties, bn.reviews_after), ""]
L += ["**Implied change in the gap by county Trump share (shared baseline, average of the two events)**", "", "| Trump share | Change in WPME-minus-ME gap | p |", "|---|---|---|"]
for _, r in sb[sb.quantity.str.startswith("implied")].iterrows():
    L.append("| %s | %s | %s |" % (r.quantity.split(" at ")[1].split(" Trump")[0], fe(r.est), fp(r.p)))
w = pd.read_csv(OUT / "exhibit3_which_group_moves.csv")
w = w[w.me_list.eq("national")]
L += ["", "**Which group moves** (relative to American-first restaurants in the same county and period; %d WPME, %d ME, %d American)" % (w.n_wpme.iloc[0], w.n_me.iloc[0], w.n_american.iloc[0]), "",
      "| Quantity | Estimate | SE | p |", "|---|---|---|---|"]
for _, r in w.iterrows():
    L.append("| %s | %s | %.3f | %s |" % (r.quantity, fe(r.est), r.se, fp(r.p)))
g = pd.read_csv(OUT / "exhibit3_gap_levels.csv")
g = g[g.me_list.eq("national")]
L += ["", "**Gap levels by window** (WPME minus ME, restaurant mean rating in the window, county fixed effects)", "", "| Window | Quantity | Estimate | p |", "|---|---|---|---|"]
for win in ["210 days before the election", "6 weeks after the election", "6 weeks after the travel ban"]:
    for _, r in g[g.window.eq(win)].iterrows():
        L.append("| %s | %s | %s | %s |" % (win, r.quantity, fe(r.est), fp(r.p)))
o = pd.read_csv(OUT / "exhibit3_ordinary_dates.csv")
o = o[o.trump_measure.eq("continuous") & ~o.overlaps_event]
L += ["", "**Ordinary dates.** The same model on %d dates with no event: mean %s, SD %.3f, range %s to %s; %d significant at .05." % (
    len(o), fe(o.est.mean()), o.est.std(), fe(o.est.min()), fe(o.est.max()), int(o.p.lt(.05).sum())), ""]
L += ["**Other events tested (not in focus)**", "", "| Event | Per 10 pts Trump share, first 6 weeks | p |", "|---|---|---|"]
for name, lab in [("Travel ban 2.0", "Travel ban 2.0 (Mar 6, 2017)"), ("Travel ban 3.0", "Travel ban 3.0 (Sep 24, 2017)"), ("Supreme Court ruling", "Supreme Court ruling (Jun 26, 2018)"),
                  ("Soleimani strike", "Soleimani strike (Jan 3, 2020)"), ("POOLED: all six events", "All six events pooled")]:
    a = e[e.event.eq(name) & e.trump_measure.eq("continuous") & e.window.eq("first 6 weeks")].iloc[0]
    L.append("| %s | %s | %s |" % (lab, fe(a.est), fp(a.p)))
L += ["", "The focus on the election and the first travel ban was chosen after all six results were seen.", ""]
x4, c4 = pd.read_csv(OUT / "exhibit4_positioning_over_time.csv"), pd.read_csv(OUT / "exhibit4_cohorts.csv")
x4 = x4[x4.me_list.eq("national") & x4.control.eq("no review-count control")]
L += ["## Exhibit 4. Positioning over time", "",
      "Categories are a 2021 snapshot, so relabeling is not observable. Each restaurant's first review date stands in for when it opened. "
      "Outcome: 1 if WPME, 0 if ME. After = first reviewed on or after Nov 8, 2016. County fixed effects; the Trump interactions add first-review-year fixed effects. Coefficients in percentage points.", "",
      "| Sample | Window | Before / after (n) | Share WPME before | after | After | p | After x 10 pts Trump share | p | After x Trump share above 50% | p |", "|---|---|---|---|---|---|---|---|---|---|---|"]
for comp in x4.comparison.unique():
    for win in x4.window.unique():
        g = lambda mdl: x4[x4.comparison.eq(comp) & x4.window.eq(win) & x4.model.eq(mdl)].iloc[0]
        a, t, j = g("overall: After"), g("by Trump: After x continuous"), g("by Trump: After x majority")
        L.append("| %s | %s | %d / %d | %.0f%% | %.0f%% | %s | %s | %s | %s | %s | %s |" % (comp, win, a.n_before, a.n_after, 100 * a.share_before, 100 * a.share_after,
                 fe(100 * a.est, 1), fp(a.p), fe(100 * t.est, 1), fp(t.p), fe(100 * j.est, 1), fp(j.p)))
c4 = c4[c4.me_list.eq("national") & c4.comparison.eq("WPME vs all ME") & c4.first_review_year.between(2012, 2020)]
yrs = sorted(c4.first_review_year.unique())
L += ["", "**Share WPME by year of first review**", "", "| County | " + " | ".join(str(y) for y in yrs) + " |", "|---|" + "---|" * len(yrs)]
for ct in ["Trump share 50% or less", "Trump share above 50%"]:
    d = c4[c4.county_type.eq(ct)].set_index("first_review_year")
    L.append("| %s | %s |" % (ct, " | ".join("%.0f%% (%d)" % (100 * d.loc[y, "share_wpme"], d.loc[y, "restaurants"]) for y in yrs)))
L += ["", "Restaurants in parentheses. Controlling for log review count changes the overall estimate to %s points (p = %s) in the two-year window." % (
    fe(100 * pd.read_csv(OUT / "exhibit4_positioning_over_time.csv").query("me_list == 'national' and comparison == 'WPME vs all ME' and window.str.contains('2 years') and model == 'overall: After' and control == 'controlling log review count'", engine="python").est.iloc[0], 1),
    fp(pd.read_csv(OUT / "exhibit4_positioning_over_time.csv").query("me_list == 'national' and comparison == 'WPME vs all ME' and window.str.contains('2 years') and model == 'overall: After' and control == 'controlling log review count'", engine="python").p.iloc[0])), "",
      "## Original 20-category ME list", "", "| Quantity | Estimate | p |", "|---|---|---|"]
eo = pd.read_csv(OUT / "exhibit3_events.csv")
eo = eo[eo.me_list.eq("original") & eo.trump_measure.eq("continuous") & eo.window.eq("first 6 weeks")].set_index("event")
mo = m[m.me_list.eq("original") & m.trump_measure.eq("continuous") & m.controls.eq("+ college, foreign-born")].iloc[0]
vo = pd.read_csv(OUT / "exhibit2_levels.csv")
vo = vo[vo.me_list.eq("original") & vo.comparison.eq("WPME vs all ME") & vo.outcome.eq("mean_rating") & vo.quantity.eq("gap, all counties")].iloc[0]
L += ["| Label choice: per 1 pt Middle Eastern ancestry (pts) | %s | %s |" % (fe(100 * mo.mena_est, 1), fp(mo.mena_p)),
      "| Rating gap, all counties | %s | %s |" % (fe(vo.est), fp(vo.p)),
      "| Election, per 10 pts | %s | %s |" % (fe(eo.loc["2016 election", "est"]), fp(eo.loc["2016 election", "p"])),
      "| Travel ban, per 10 pts | %s | %s |" % (fe(eo.loc["Travel ban", "est"]), fp(eo.loc["Travel ban", "p"])),
      "| Both pooled, per 10 pts | %s | %s |" % (fe(eo.loc["POOLED: election and travel ban", "est"]), fp(eo.loc["POOLED: election and travel ban", "p"])), ""]
(HERE / "RESULTS.md").write_text("\n".join(L), encoding="utf-8")
print("RESULTS.md written, %d lines" % len(L))
